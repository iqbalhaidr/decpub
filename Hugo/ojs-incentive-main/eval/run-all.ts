/**
 * eval/run-all.ts — Headless evaluation harness for thesis Bab IV.
 *
 * Regenerates every middleware-derived number in the evaluation chapter from
 * the committed datasets and the real production engine (../middleware), then
 * writes a single machine-readable artifact to eval-output/eval-results.json.
 *
 * Covers: IV.3.1 CR, IV.3.2 Spearman, IV.3.3 lambda, IV.3.4 ECWM-adaptif,
 *         IV.4.1 free-riding, IV.4.2 Sybil, IV.4.3 decay, IV.4.4 sensitivity,
 *         IV.4.5 robustness.
 *
 * The on-chain gas figures (IV.5) are produced separately by the Hardhat test
 * (npm run eval:gas) because they require the EVM runtime.
 *
 * Run: npm run eval   (or  npx ts-node eval/run-all.ts)
 */

import * as fs from "fs";
import * as path from "path";
import { EVAL, EVAL_L, FR, FR_L, SYB, SYB_L, PRESETS } from "../frontend/config/eval-datasets";
import { runPipeline, runBaselines, runMulticycle } from "./core";
import { runEcwmAdaptive } from "./ecwm-adaptive";
import { runSensitivity } from "./sensitivity";
import { runRobustness } from "./robustness";

const bwmOf = (p: any) => ({ bestIndex: p.best, worstIndex: p.worst, bestToOthers: p.bo, othersToWorst: p.ow });

// ---- IV.3.1 CR per preset ----
const cr = Object.keys(PRESETS).map((name) => ({
  preset: name,
  cr: runPipeline(EVAL, { bwm: bwmOf(PRESETS[name]) }).bwmCR,
}));

// ---- IV.3.2 Spearman vs hybrid ----
const spearman = runBaselines(EVAL).baselines.map((b) => ({ method: b.method, spearman: b.spearman }));

// ---- IV.3.3 lambda sensitivity ----
const lambda = [0, 0.3, 0.5, 0.6, 0.7, 1.0].map((lam) => {
  const d = runPipeline(EVAL, { lambda: lam });
  return { lambda: lam, scores: d.topsisScores, winner: EVAL_L[d.ranking[0]] };
});

// ---- IV.3.4 ECWM adaptif ----
const ecwmAdaptive = runEcwmAdaptive();

// ---- IV.4.1 free-riding: sigmoid vs linear ----
const frBase = runBaselines(FR);
const freeRiding = {
  labels: FR_L,
  sigmoid: frBase.hybrid.rewards,
  linear: (frBase.baselines.find((b) => /Linear/.test(b.method)) as any).rewards,
};

// ---- IV.4.2 Sybil ----
const sybil = { labels: SYB_L, rewards: runPipeline(SYB).rewards };

// ---- IV.4.3 decay multicycle ----
const decayRun = runMulticycle({ numCycles: 10 });
const decay = {
  names: decayRun.reviewerNames,
  perCycle: decayRun.cycles.map((c: any) => ({ cycle: c.cycle, sbt: c.sbtBalances, eveInactive: c.eveInactive })),
};

// ---- IV.4.4 sensitivity sweep ----
const sensitivity = runSensitivity();

// ---- IV.4.5 robustness ----
const robustness = runRobustness();

const results = {
  generatedBy: "eval/run-all.ts",
  engine: "../middleware (production)",
  note: "Gas figures (IV.5) are generated by npm run eval:gas (Hardhat).",
  defaults: { lambda: 0.6, gamma: 0.5, sigmoidK: 10, sigmoidX0: 0.5, pool: 2.0, decayRate: 0.02 },
  IV_3_1_cr: cr,
  IV_3_2_spearman: spearman,
  IV_3_3_lambda: lambda,
  IV_3_4_ecwmAdaptive: ecwmAdaptive,
  IV_4_1_freeRiding: freeRiding,
  IV_4_2_sybil: sybil,
  IV_4_3_decay: decay,
  IV_4_4_sensitivity: sensitivity,
  IV_4_5_robustness: robustness,
};

const outDir = path.join(__dirname, "..", "eval-output");
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "eval-results.json");
fs.writeFileSync(outFile, JSON.stringify(results, null, 2));

console.log("\n  Evaluation harness — Bab IV (middleware-derived numbers)");
console.log("  " + "-".repeat(58));
console.log(`  IV.3.1 CR (all presets)      : ${cr.every((c) => c.cr < 1e-9) ? "all 0.000" : "see file"}`);
console.log(`  IV.3.2 Spearman WSM vs hybrid: ${(spearman.find((s) => /WSM/.test(s.method)) as any).spearman.toFixed(3)}`);
console.log(`  IV.3.3 lambda winner         : ${lambda.every((l) => l.winner === lambda[0].winner) ? `${lambda[0].winner} (stable)` : "varies"}`);
console.log(`  IV.3.4 ECWM q1-uniform w_q1  : ${ecwmAdaptive[1].weights[0].toFixed(3)} (→0 expected)`);
console.log(`  IV.4.1 ratio sigmoid/linear  : see file`);
console.log(`  IV.4.2 Sybil rewards         : ${sybil.rewards.map((r) => r.toFixed(3)).join(", ")}`);
console.log(`  IV.4.3 decay Eve cyc1→cyc10  : ${decay.perCycle[0].sbt[4].toFixed(3)} → ${decay.perCycle[9].sbt[4].toFixed(3)}`);
console.log(`  IV.4.4 k-sweep ratios        : ${sensitivity.k.map((r) => r.ratio.toFixed(2)).join(" / ")}`);
console.log(`  IV.4.5 robustness FR-smallest: ${robustness.freeRiderSmallest.count}/${robustness.freeRiderSmallest.total}`);
console.log("  " + "-".repeat(58));
console.log(`  Artifact written: ${path.relative(path.join(__dirname, ".."), outFile)}\n`);
